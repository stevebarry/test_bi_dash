-- Sample retail database: customers, stores, products, orders.
-- Re-runnable: rebuilds only the tables and view below in the existing
-- "sales" schema (which must already exist). Other objects in the schema are
-- left alone; if one of them depends on these tables, the DROP fails rather
-- than cascading.

DROP VIEW IF EXISTS sales.order_totals;
DROP TABLE IF EXISTS sales.order_items;
DROP TABLE IF EXISTS sales.orders;
DROP TABLE IF EXISTS sales.customers;
DROP TABLE IF EXISTS sales.products;
DROP TABLE IF EXISTS sales.stores;

CREATE TABLE sales.stores (
    store_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text        NOT NULL,
    address      text        NOT NULL,
    city         text        NOT NULL,
    state        char(2)     NOT NULL,
    postal_code  varchar(10) NOT NULL,
    phone        text,
    opened_date  date        NOT NULL
);

CREATE TABLE sales.customers (
    customer_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   text        NOT NULL,
    last_name    text        NOT NULL,
    email        text        NOT NULL UNIQUE,
    phone        text,
    address      text,
    city         text,
    state        char(2),
    postal_code  varchar(10),
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sales.products (
    product_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text          NOT NULL UNIQUE,
    name         text          NOT NULL,
    category     text          NOT NULL,
    unit_price   numeric(10,2) NOT NULL CHECK (unit_price > 0),
    active       boolean       NOT NULL DEFAULT true
);

CREATE TABLE sales.orders (
    order_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer     NOT NULL REFERENCES sales.customers (customer_id),
    store_id     integer     NOT NULL REFERENCES sales.stores (store_id),
    order_date   timestamptz NOT NULL,
    status       text        NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'shipped', 'delivered', 'cancelled'))
);

CREATE TABLE sales.order_items (
    order_id     integer       NOT NULL REFERENCES sales.orders (order_id) ON DELETE CASCADE,
    product_id   integer       NOT NULL REFERENCES sales.products (product_id),
    quantity     integer       NOT NULL CHECK (quantity > 0),
    unit_price   numeric(10,2) NOT NULL CHECK (unit_price > 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE INDEX ON sales.orders (customer_id);
CREATE INDEX ON sales.orders (store_id);
CREATE INDEX ON sales.orders (order_date);
CREATE INDEX ON sales.order_items (product_id);

CREATE VIEW sales.order_totals AS
SELECT order_id, sum(quantity * unit_price)::numeric(12,2) AS total
FROM sales.order_items
GROUP BY order_id;
